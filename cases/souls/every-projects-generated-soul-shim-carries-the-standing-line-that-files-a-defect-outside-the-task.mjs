// protects: /home/lyphe/.claude/charters/CONSTRAINTS.md, /home/lyphe/.claude/scripts/generate_soul_agents.py, /home/lyphe/.claude/hooks/regenerate_soul_shims.py, /opt/shadow-connector/.claude/agents/
// writes: none
//
// A project's own generated shim (/opt/<repo>/.claude/agents/<soul>.md) OUTRANKS the user-global shim of the same
// name, so a soul launched in that project reads its law from the project shim alone. The regenerate hook rebuilds
// a project's shims on a CONSTRAINTS.md edit only for the project the editing session stands in, so a constraints
// line added from ~/.claude reaches ~/.claude/agents and never the connector's thoth and vitruvius (measured
// 2026-11-19). This case finds the standing bug-file line in CONSTRAINTS.md and requires it, verbatim, in every
// generated shim of every project agents folder: each /opt/<repo>/.claude/agents and the CloudCLI repo's. Read-only.
// Hand-written project agents (no GENERATED header in their first sixteen lines) are not the generator's and are
// not judged.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";

import { broken, held, runCase } from "../lib/case.mjs";

const HOME = path.join(os.homedir(), ".claude");
const CONSTRAINTS = path.join(HOME, "charters", "CONSTRAINTS.md");
const MARK = "GENERATED by";

const isDir = (p) => {
  try { return fs.statSync(p).isDirectory(); } catch { return false; }
};

function projectAgentDirs() {
  const dirs = [path.join(HOME, "claudecodeui_lyphe", ".claude", "agents")];
  for (const entry of fs.readdirSync("/opt")) dirs.push(path.join("/opt", entry, ".claude", "agents"));
  return dirs.filter(isDir);
}

runCase(async () => {
  const charter = fs.readFileSync(CONSTRAINTS, "utf8");
  const line = charter.split("\n").map((l) => l.trim()).find((l) =>
    l.includes("~/.claude/scripts/bug file") && /defect outside your task/i.test(l) && /report/.test(l) && /not fixed in passing/.test(l));
  if (!line) return broken("charters/CONSTRAINTS.md holds no line filing a defect outside the task with ~/.claude/scripts/bug file");

  let generated = 0;
  const lacking = [];
  for (const dir of projectAgentDirs()) {
    for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".md")).sort()) {
      const text = fs.readFileSync(path.join(dir, file), "utf8");
      if (!text.split("\n", 16).join("\n").includes(MARK)) continue;
      generated += 1;
      if (!text.includes(line)) lacking.push(path.join(dir, file));
    }
  }
  if (generated === 0) return held("no project agents folder holds a generated shim, so none can lack the line");
  if (lacking.length > 0) {
    return broken(`${lacking.length} of ${generated} generated project shims lack the line (${lacking.join(", ")}) — regenerate with scripts/generate_soul_agents.py --project <repo>`);
  }
  return held(`the line is in all ${generated} generated project shims`);
});
