// protects: /home/lyphe/.claude/charters/CONSTRAINTS.md, /home/lyphe/.claude/scripts/generate_soul_agents.py, /home/lyphe/.claude/agents/
// writes: none
//
// Every soul carries the standing constraints in its shim, and the shims are GENERATED from charters/CONSTRAINTS.md,
// never hand-edited. The line this plan added — a defect outside your task is filed with `~/.claude/scripts/bug file`
// from the folder it is in, named in your report, and not fixed in passing when the fix is more than a few minutes —
// is found in CONSTRAINTS.md, then looked for verbatim in two places: every shim the generator's own `generate()`
// writes into a scratch agents folder (so a generator that stops carrying the block breaks this), and every
// generated shim in ~/.claude/agents (the files a soul is actually launched from). The live shims are only read.

import { spawn } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

import { broken, held, runCase } from "../lib/case.mjs";
import { scratchDir } from "../lib/scratch.mjs";

const HOME = path.join(os.homedir(), ".claude");
const CONSTRAINTS = path.join(HOME, "charters", "CONSTRAINTS.md");
const AGENTS = path.join(HOME, "agents");
const MARK = "GENERATED by ~/.claude/scripts/generate_soul_agents.py";

// generate() into the folder named by argv[1]; prints the souls it wrote as JSON. The live table is read, never
// a scratch one, and the live agents folder is never the target.
const GENERATE = `
import json, os, sys
from pathlib import Path
sys.path.insert(0, os.path.expanduser("~/.claude/scripts"))
from load_module import load_file
gen = load_file(os.path.expanduser("~/.claude/scripts/generate_soul_agents.py"))
out = Path(sys.argv[1])
assert os.path.realpath(out) != os.path.realpath(gen.USER_AGENTS)
done = gen.generate(gen.USER_CHARTERS, out, gen._read_table())
print(json.dumps({"written": done.written, "kept": done.kept}))
`;

function run(file, args, env) {
  return new Promise((resolve) => {
    const child = spawn(file, args, { env, stdio: ["ignore", "pipe", "pipe"] });
    let out = "";
    let err = "";
    const timer = setTimeout(() => child.kill("SIGKILL"), 60000);
    child.stdout.on("data", (b) => { out += b; });
    child.stderr.on("data", (b) => { err += b; });
    child.on("error", (e) => { clearTimeout(timer); resolve({ code: null, out, err: `${err}${e.message}` }); });
    child.on("close", (code) => { clearTimeout(timer); resolve({ code, out, err }); });
  });
}

runCase(async (t) => {
  const charter = fs.readFileSync(CONSTRAINTS, "utf8");
  const line = charter.split("\n").map((l) => l.trim()).find((l) =>
    l.includes("~/.claude/scripts/bug file") && /defect outside your task/i.test(l) && /report/.test(l) && /not fixed in passing/.test(l));
  if (!line) return broken("charters/CONSTRAINTS.md holds no line filing a defect outside the task with ~/.claude/scripts/bug file, named in the report and not fixed in passing");

  const dir = await scratchDir(t, "shims");
  const env = { ...process.env };
  delete env.LAUNCH_TABLE_PATH;
  const gen = await run("python3", ["-c", GENERATE, path.join(dir, "agents")], env);
  let made;
  try { made = JSON.parse(gen.out.trim().split("\n").pop()); } catch { made = null; }
  if (gen.code !== 0 || !made || made.written.length === 0) {
    return broken(`the generator wrote no shim into scratch — exit ${gen.code}: ${`${gen.out}${gen.err}`.trim().slice(-300)}`);
  }

  const wrong = [];
  const scratchLacking = made.written.filter((name) => !fs.readFileSync(path.join(dir, "agents", `${name}.md`), "utf8").includes(line));
  if (scratchLacking.length) wrong.push(`${scratchLacking.length} of ${made.written.length} freshly generated shims lack the line (${scratchLacking.join(", ")})`);

  const live = fs.readdirSync(AGENTS).filter((f) => f.endsWith(".md")).filter((f) => fs.readFileSync(path.join(AGENTS, f), "utf8").includes(MARK));
  if (live.length === 0) wrong.push("~/.claude/agents holds no generated shim");
  const liveLacking = live.filter((f) => !fs.readFileSync(path.join(AGENTS, f), "utf8").includes(line));
  if (liveLacking.length) wrong.push(`${liveLacking.length} of ${live.length} live shims in ~/.claude/agents lack the line (${liveLacking.join(", ")}) — regenerate them with scripts/generate_soul_agents.py`);

  if (wrong.length > 0) return broken(wrong.join("; "));
  return held(`the line is in all ${made.written.length} freshly generated shims and all ${live.length} live ones`);
});
